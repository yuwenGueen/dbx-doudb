import assert from 'node:assert/strict';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join, basename } from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));
const manifest=JSON.parse(await readFile(join(root,'manifest.json'),'utf8'));
const tag=process.env.GITHUB_REF_NAME || `v${manifest.version}`;
const repository=process.env.GITHUB_REPOSITORY || 'yuwenGueen/dbx-doudb';
assert.equal(tag,`v${manifest.version}`,'Release tag must match manifest version');
assert.match(repository,/^[\w.-]+\/[\w.-]+$/);
const files=(await readdir(join(root,'dist'))).filter(f=>f.startsWith(`${manifest.id}-${manifest.version}-`)&&f.endsWith('.artifact.json'));
assert.ok(files.length,'No candidate metadata files found');
const artifacts=[];
for(const file of files){
  const metadata=JSON.parse(await readFile(join(root,'dist',file),'utf8'));
  assert.equal(metadata.signingKeyId,undefined,'Candidates must be unsigned');
  const name=basename(new URL(metadata.url,'https://example.invalid/').pathname);
  const packagePath=join(root,'dist',name);
  const bytes=await readFile(packagePath);
  assert.equal(metadata.size,bytes.length);
  assert.equal(metadata.sha256,createHash('sha256').update(bytes).digest('hex'));
  const entries=execFileSync('unzip',['-Z1',packagePath],{encoding:'utf8'}).trim().split(/\r?\n/);
  assert.ok(!entries.includes('signature.json'));
  assert.ok(!entries.some(f=>f.includes('.dbx-dev')||f.endsWith('.env')));
  const packed=JSON.parse(execFileSync('unzip',['-p',packagePath,'manifest.json'],{encoding:'utf8'}));
  for(const key of ['id','publisher','version'])assert.equal(packed[key],manifest[key]);
  assert.deepEqual(packed.permissions,manifest.permissions);
  assert.ok(entries.includes(packed.entrypoints.backend.executable));
  assert.equal(metadata.target,'darwin-arm64','Only the validated initial platform is released');
  metadata.url=`https://github.com/${repository}/releases/download/${tag}/${name}`;
  artifacts.push(metadata);
  await writeFile(join(root,'dist',file),JSON.stringify(metadata,null,2)+'\n');
}
assert.equal(new Set(artifacts.map(a=>a.target)).size,artifacts.length);
const plugin=Object.fromEntries(['id','name','description','publisher','version','permissions'].map(k=>[k,manifest[k]]));
await writeFile(join(root,'dist/release-candidates.json'),JSON.stringify({plugin,artifacts},null,2)+'\n');
console.log(`Verified ${artifacts.length} unsigned candidate(s) for ${manifest.id}@${manifest.version}`);
